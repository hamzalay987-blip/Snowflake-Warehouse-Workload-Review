-- Read-only example; requires ACCOUNT_USAGE visibility and appropriate permissions.
SELECT QUERY_PARAMETERIZED_HASH, COUNT(*) AS RUNS, AVG(TOTAL_ELAPSED_TIME)/1000 AS AVG_SECONDS,
       SUM(CREDITS_ATTRIBUTED_COMPUTE) AS COMPUTE_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY
WHERE START_TIME >= DATEADD(day,-7,CURRENT_TIMESTAMP())
GROUP BY 1 ORDER BY COMPUTE_CREDITS DESC;
